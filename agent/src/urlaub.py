def build_urlaubsantwort(
    original,
    text: str,
    own_email: str,
    own_display_name: str,
) -> bytes:
    """Fertige RFC-5322-Bytes der Autoantwort.

    Zwei bewusste Unterschiede zu `draft.build_reply_draft`:

    * **Kein Zitat des Originals.** Eine Abwesenheitsnotiz schickt dem Absender
      seine eigene Mail nicht zurueck — und je weniger Inhalt hinausgeht, desto
      kleiner der Datenschutz-Fussabdruck dieser einen Ausnahme.
    * **Automatik-Kopfzeilen** (RFC 3834): `Auto-Submitted: auto-replied` ist
      der Header, an dem eine regelkonforme Gegenstelle erkennt, dass sie
      NICHT zurueckantworten darf. `X-Auto-Response-Suppress: All` ist das
      Aequivalent fuer Outlook/Exchange, `Precedence: bulk` das aeltere,
      breit verstandene Signal.

    Threading (`In-Reply-To`/`References`) bleibt erhalten: die Antwort soll im
    Mail-Programm des Absenders am richtigen Gespraech haengen."""
    msg = EmailMessage()

    if own_display_name:
        from_header = formataddr((_sanitize_header(own_display_name), _sanitize_header(own_email)))
    else:
        from_header = _sanitize_addr(own_email)
    msg["From"] = from_header
    msg["To"] = _sanitize_addr(str(getattr(original, "from_", "") or ""))
    msg["Subject"] = _sanitize_header(_betreff(getattr(original, "subject", "") or ""))
    msg["Date"] = format_datetime(datetime.now(timezone.utc))
    msg["Message-ID"] = make_msgid(
        domain=own_email.split("@")[-1] if "@" in own_email else "localhost"
    )

    original_msg_id = _sanitize_header(_header(original, "message-id"))
    if original_msg_id:
        msg["In-Reply-To"] = original_msg_id
        refs = _sanitize_header(_header(original, "references"))
        msg["References"] = f"{refs} {original_msg_id}".strip() if refs else original_msg_id

    # Schleifenschutz-Kopfzeilen (RFC 3834 / Exchange / historisch).
    msg["Auto-Submitted"] = "auto-replied"
    msg["X-Auto-Response-Suppress"] = "All"
    msg["Precedence"] = "bulk"

    msg.set_content(text.strip() + "\n", subtype="plain", charset="utf-8")
    return bytes(msg)


def _betreff(original_betreff: str) -> str:
    roh = (original_betreff or "").strip()
    if not roh:
        return "Abwesenheitsnotiz"
    niedrig = roh.casefold()
    if niedrig.startswith("re:") or niedrig.startswith("aw:"):
        return roh
    return f"Re: {roh}"


