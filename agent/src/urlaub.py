# Wie weit ein Zyklus zurueckschaut. Bewusst KEINE Env-Variable: der Agent
# pollt alle 5 Minuten, 24 h Puffer deckt einen halben Ausfalltag ab, und die
# Merkliste verhindert ohnehin Doppelantworten. Ein groesserer Wert haette
# einen unangenehmen Nebeneffekt — wer den Urlaub NACHTRAEGLICH eintraegt,
# wuerde rueckwirkend Antworten auf laengst gelesene Mails ausloesen.
LOOKBACK_STUNDEN = 24

# Absender-Localparts, die nie eine Antwort bekommen (Praefix-Vergleich).
NO_REPLY_PRAEFIXE = (
    "no-reply",
    "noreply",
    "no_reply",
    "donotreply",
    "do-not-reply",
    "do_not_reply",
    "mailer-daemon",
    "mailerdaemon",
    "postmaster",
    "bounce",
    "bounces",
    "abuse",
)

# `Precedence`-Werte, die eine Massen-/Automatenmail kennzeichnen.
MASSEN_PRECEDENCE = ("bulk", "list", "junk", "auto_reply", "auto-reply")

# `List-*`-Header: jeder einzelne davon macht die Mail zu Listenpost.
LISTEN_HEADER = ("list-id", "list-unsubscribe", "list-post", "list-help", "list-subscribe")

# Header, die eine Gegenstelle setzt, die selbst gerade automatisch antwortet.
AUTOMATIK_HEADER = ("x-autoreply", "x-autorespond", "x-autogenerated", "x-auto-response-suppress")

# Betreff-Muster als LETZTE Verteidigungslinie fuer Gegenstellen, die gar keine
# RFC-3834-Header setzen (aeltere Exchange-Regeln, selbstgebaute Skripte).
_ABWESENHEITS_BETREFF = re.compile(
    r"^\s*(re:\s*|aw:\s*|fwd?:\s*|wg:\s*)*"
    r"(auto(matische|matic)?[\s:_-]|abwesenheit|abwesend|out\s+of\s+office|"
    r"ooo\b|urlaubsbenachrichtigung|undeliverable|delivery\s+status|"
    r"mail\s+delivery\s+failed|returned\s+mail|zustellung|unzustellbar)",
    re.IGNORECASE,
)

DATUM_MUSTER = re.compile(r"^\d{4}-\d{2}-\d{2}$")


