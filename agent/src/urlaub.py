"""Urlaubs-Autoantwort (URL-01..09) — die eine Ausnahme von „kein Auto-Send".

Betreiber-Wunsch vom 2026-08-22: „der agent soll auch auto-entwuerfe fuer die
urlaubszeit haben, sprich im backend urlaub sollte irgendwo eintragbar sein, so
dass automatische emails rausgesendet werden (einzige ausnahme) mit einem
vorlage text aus vorlagen `## urlaub`".

## Was hier NICHT passiert

Gesendet wird in diesem Modul nichts. Es baut die fertige Mail und uebergibt
sie an `mail_relay.urlaubsantwort_ausliefern`, das sie an den WebUI-Service
weiterreicht; nur dort (in `webui/src/mail_send.py`) spricht das Produkt SMTP.
`agent/src/` bleibt strukturell SMTP-frei — siehe den ausfuehrlichen
Modul-Docstring in `mail_relay.py`.

## Die vier Riegel

1. `ENABLE_URLAUBSANTWORT` (Default **aus**) — das Freigabe-Gate, nur im
   Einstellungen-Fenster umlegbar, bewusst NICHT ueber den Chat.
2. Ein gesetzter, gueltiger und HEUTE laufender Zeitraum (`URLAUB_VON`/
   `URLAUB_BIS`, `JJJJ-MM-TT`).
3. Ein `## Urlaub`-Abschnitt in `vorlagen.md`. Fehlt er, wird NICHT gesendet
   und kein Platzhaltertext erfunden.
4. `URLAUB_DRY_RUN` (Default **an**) — der Probelauf protokolliert vollstaendig
   (inklusive der Empfaenger, die eine Antwort BEKAEMEN) und liefert nichts aus.

## Der Schleifenschutz (URL-05, der eigentliche Risikoblock)

Eine Autoantwort, die eine Autoantwort beantwortet, laeuft zwischen zwei
Postfaechern endlos. Deshalb:

* Die eigene Antwort traegt `Auto-Submitted: auto-replied` (RFC 3834),
  `X-Auto-Response-Suppress: All` und `Precedence: bulk` — eine
  regelkonforme Gegenstelle antwortet darauf nicht mehr.
* Eingehend wird JEDE Mail uebersprungen, die selbst maschinell aussieht:
  `Auto-Submitted` ungleich `no`, `Precedence: bulk/list/junk/auto_reply`,
  irgendein `List-*`-Header, `X-Autoreply`/`X-Autorespond`/`X-Autogenerated`,
  ein leerer `Return-Path` (Bounce) oder ein Betreff im typischen
  Abwesenheits-/Bounce-Wortlaut.
* Absender wie `no-reply@`, `mailer-daemon@`, `postmaster@`, `bounce@`
  bekommen nie eine Antwort.
* Steht das eigene Postfach nicht im `To`, sondern nur im `Cc`/`Bcc`, wird
  nicht geantwortet — sonst platzt die Autoantwort in fremde Threads.
* Und der harte Riegel: **einmal pro Absender pro Urlaubszeitraum**
  (`state.urlaub_antworten`). Selbst wenn alle Kopfzeilen-Pruefungen versagen,
  kann zwischen zwei Postfaechern hoechstens EINE Antwort je Richtung
  entstehen.
* Dazu ein Deckel pro Zyklus (`URLAUB_MAX_PRO_ZYKLUS`, Default 20).
"""
