def _header(msg, name: str) -> str:
    """Ein Header-Wert als String. `imap-tools` liefert je nach Version tuple
    ODER list ODER str — alle drei normalisieren (dieselbe Falle wie in
    `main._process_one`, CR-01)."""
    roh = msg.headers.get(name, "") if hasattr(msg, "headers") else ""
    if isinstance(roh, (tuple, list)):
        roh = roh[0] if roh else ""
    return (roh or "").strip()


def ist_automatische_mail(msg) -> tuple[bool, str]:
    """`(True, Grund)`, wenn die Mail selbst maschinell erzeugt aussieht.

    Der Grund wandert ins Log und in den Probelauf-Bericht — der Betreiber
    soll sehen, WARUM eine Mail uebersprungen wurde, statt nur zu bemerken,
    dass jemand keine Antwort bekam."""
    auto_submitted = _header(msg, "auto-submitted").casefold()
    if auto_submitted and auto_submitted != "no":
        return True, f"Auto-Submitted: {auto_submitted}"

    precedence = _header(msg, "precedence").casefold()
    if precedence in MASSEN_PRECEDENCE:
        return True, f"Precedence: {precedence}"

    for name in LISTEN_HEADER:
        if _header(msg, name):
            return True, f"Listenpost ({name})"

    for name in AUTOMATIK_HEADER:
        wert = _header(msg, name).casefold()
        if wert and wert != "no":
            return True, f"{name}: {wert}"

    # Leerer Return-Path (`<>`) ist die Envelope-Signatur einer Zustellmeldung.
    return_path = _header(msg, "return-path").strip()
    if return_path in ("<>", "<MAILER-DAEMON>"):
        return True, "Leerer Return-Path (Zustellmeldung)"

    if _header(msg, "x-failed-recipients"):
        return True, "Zustellmeldung (X-Failed-Recipients)"

    betreff = (getattr(msg, "subject", "") or "").strip()
    if betreff and _ABWESENHEITS_BETREFF.match(betreff):
        return True, "Betreff sieht nach Abwesenheits-/Zustellmeldung aus"

    return False, ""


def ist_no_reply_adresse(adresse: str) -> bool:
    """Praefix-Vergleich auf dem Localpart. `noreply-service@x.de` faellt damit
    ebenso raus wie `noreply@x.de`."""
    _, addr = parseaddr((adresse or "").strip())
    localpart = (addr or adresse or "").split("@")[0].strip().casefold()
    if not localpart:
        return False
    return any(localpart.startswith(p) for p in NO_REPLY_PRAEFIXE)


def _adressmenge(*werte) -> set[str]:
    """Alle Mailadressen aus beliebigen Header-Werten (str, tuple, list) als
    casefolded Menge."""
    roh: list[str] = []
    for wert in werte:
        if not wert:
            continue
        if isinstance(wert, (tuple, list)):
            roh.extend(str(w) for w in wert if w)
        else:
            roh.append(str(wert))
    treffer = set()
    for _, addr in getaddresses(roh):
        if addr:
            treffer.add(addr.strip().casefold())
    return treffer


def direkt_adressiert(msg, eigene_adressen: set[str]) -> bool:
    """True, wenn eines der eigenen Postfaecher im `To` steht.

    Bewusst streng: steht das eigene Postfach nur im `Cc` (oder gar nicht,
    weil es per `Bcc`/Verteiler ankam), platzt eine Autoantwort in einen
    fremden Thread und schreibt womoeglich Menschen an, die den Betreiber gar
    nicht angeschrieben haben."""
    empfaenger = _adressmenge(getattr(msg, "to", None), _header(msg, "to"))
    return bool(empfaenger & eigene_adressen)


def eigene_adressen(config: Config) -> set[str]:
    """`OWN_EMAIL_ADDRESS` plus `IMAP_USER` — bei einem Alias-Setup weichen
    beide voneinander ab, und beide sind legitime Empfangsadressen."""
    menge = set()
    for wert in (config.own_email_address, config.imap_user):
        _, addr = parseaddr((wert or "").strip())
        gewaehlt = (addr or wert or "").strip().casefold()
        if gewaehlt:
            menge.add(gewaehlt)
    return menge


def antwort_faellig(msg, config: Config, eigene: set[str]) -> tuple[bool, str]:
    """Alle Kopfzeilen-Pruefungen in einem Aufruf. `(False, Grund)` heisst
    "nicht antworten"; der Grund ist fuer Log/Probelauf gedacht.

    Die Merklisten-Pruefung (einmal pro Absender) steckt NICHT hier, sondern in
    `run_urlaubsantwort` — sie braucht die Datenbank."""
    absender_roh = str(getattr(msg, "from_", "") or "").strip()
    if not absender_roh:
        return False, "Kein Absender"

    _, absender = parseaddr(absender_roh)
    absender = (absender or absender_roh).strip()
    if not absender or "@" not in absender:
        return False, "Absender ist keine Mailadresse"

    if absender.casefold() in eigene:
        return False, "Mail vom eigenen Postfach"

    if ist_no_reply_adresse(absender):
        return False, "Absender ist eine No-Reply-Adresse"

    automatisch, grund = ist_automatische_mail(msg)
    if automatisch:
        return False, grund

    if not direkt_adressiert(msg, eigene):
        return False, "Eigene Adresse steht nicht im To (nur Cc/Verteiler)"

    return True, ""


