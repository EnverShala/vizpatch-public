def parse_datum(wert: str) -> Optional[date]:
    """`JJJJ-MM-TT` -> `date`, alles andere -> None (kein Raten, kein
    Ratespiel mit `01.09.2026` vs `09/01/2026`)."""
    roh = (wert or "").strip()
    if not DATUM_MUSTER.match(roh):
        return None
    try:
        return date.fromisoformat(roh)
    except ValueError:
        return None


def zeitraum_id(von: str, bis: str) -> str:
    """Stabiler Schluessel fuer die Merkliste. Ein anderer Zeitraum ist ein
    anderer Schluessel — der naechste Urlaub beginnt also mit leerer Liste,
    ohne dass irgendwer etwas loeschen muesste."""
    return f"{(von or '').strip()}..{(bis or '').strip()}"


def zeitraum_aktiv(von: str, bis: str, heute: Optional[date] = None) -> bool:
    """`von <= heute <= bis`, beide Grenzen EINSCHLIESSLICH (der letzte
    Urlaubstag ist ein Urlaubstag).

    Bezugszeit ist die lokale Zeit des Containers (in der Regel UTC). Die
    Abweichung zur deutschen Ortszeit betraegt hoechstens zwei Stunden und
    wirkt sich nur an den Tagesgrenzen aus — dafuer bleibt der Agent frei von
    einer tzdata-Abhaengigkeit."""
    von_datum = parse_datum(von)
    bis_datum = parse_datum(bis)
    if von_datum is None or bis_datum is None or bis_datum < von_datum:
        return False
    bezug = heute or datetime.now().date()
    return von_datum <= bezug <= bis_datum


